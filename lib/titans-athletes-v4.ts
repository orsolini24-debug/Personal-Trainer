export function getAthleteV4ById(id: string): AthleteProfileV4 | undefined {
  return athleteProfilesV4.find(p => p.id === id)
}

export function getAthletesByArchetype(archetype: TitanArchetype30): AthleteProfileV4[] {
  return athleteProfilesV4.filter(p => p.primaryTitanArchetype === archetype)
}

export function getAthletesByGrit(userGritScore: number): AthleteProfileV4[] {
  return athleteProfilesV4.filter(
    p => userGritScore >= p.compatibleGritScore[0] && userGritScore <= p.compatibleGritScore[1]
  )
}

/** Returns athletes matching a specific SDT motivation type — useful for nudging strategy */
export function getAthletesByMotivation(sdt: SDTMotivationType): AthleteProfileV4[] {
  return athleteProfilesV4.filter(p => p.sdtMotivationType === sdt)
}

/** Returns athletes with specific RPE bias — useful for session load calibration */
export function getAthletesByRPEBias(bias: RPEBiasDirection): AthleteProfileV4[] {
  return athleteProfilesV4.filter(p => p.rpeBiasDirection === bias)
}

/** Fuse up to 3 athlete profiles into a composite mental model */
export function fuseAthleteProfilesV4(
  profiles: Array<{ profile: AthleteProfileV4; weight: number }>
): {
  dominantArchetype: TitanArchetype30
  blendedCDRisc: CDRiscProfile
  blendedRPEBias: RPEBiasDirection
  blendedSDT: SDTMotivationType
  activationContexts: string[]
} {
  if (profiles.length === 0) throw new Error('fuseAthleteProfilesV4: empty profiles array')

  // Dominant = highest weight
  const dominant = profiles.reduce((a, b) => (a.weight >= b.weight ? a : b))

  // CDRisc: majority vote (high > moderate > low)
  const cdCounts = { high: 0, moderate: 0, low: 0 }
  profiles.forEach(({ profile, weight }) => { cdCounts[profile.cdRiscProfile] += weight })
  const blendedCDRisc = (Object.entries(cdCounts).sort((a, b) => b[1] - a[1])[0][0]) as CDRiscProfile

  // RPEBias: majority vote
  const rpeCounts: Record<RPEBiasDirection, number> = { UNDER: 0, CALIBRATED: 0, OVER: 0 }
  profiles.forEach(({ profile, weight }) => { rpeCounts[profile.rpeBiasDirection] += weight })
  const blendedRPEBias = (Object.entries(rpeCounts).sort((a, b) => b[1] - a[1])[0][0]) as RPEBiasDirection

  return {
    dominantArchetype: dominant.profile.primaryTitanArchetype,
    blendedCDRisc,
    blendedRPEBias,
    blendedSDT: dominant.profile.sdtMotivationType,
    activationContexts: profiles.map(p => p.profile.activationContext),
  }
}
